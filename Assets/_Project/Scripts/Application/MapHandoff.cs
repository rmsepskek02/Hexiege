// ============================================================================
// MapHandoff.cs
// 로비에서 "확정된" 이번 판의 맵을 전투 씬으로 넘겨주기 위한 정적 홀더.
//
// 왜 이런 것이 필요한가:
//   맵이 정해지는 곳(로비)과 맵이 실제로 격자에 새겨지는 곳(전투 씬)이 다르다.
//   그 사이에는 LoadSceneMode.Single 씬 재로드가 있어서, 로비 씬의 오브젝트나
//   그 오브젝트가 들고 있던 참조는 전부 사라진다. 그래서 "씬을 넘어서 살아남는
//   자리"가 하나 필요하고, 그것이 이 정적 클래스다.
//
// 역할:
//   - Infrastructure 레이어(맵 전송 담당)가 Host/Client 양쪽에서 확정된 맵을 Set() 한다
//   - Bootstrap 레이어(GameBootstrapper)가 전투 씬에서 TryTake() 로 꺼내 격자에 투영한다
//
// 패턴:
//   같은 폴더의 NetworkContext 와 동일한 패턴 — 바깥 레이어가 값을 심고,
//   안쪽 레이어(또는 조합 루트)가 그 값을 읽는 정적 홀더.
//   Application 레이어이므로 Unity 엔진 타입도 Netcode 타입도 참조하지 않는다.
//   (참조하지 않는 덕분에 Unity 없이 이 파일만 따로 컴파일해서 동작을 확인할 수 있다.)
//
// Application 레이어 — 순수 C#, Unity 의존 없음.
// ============================================================================

namespace Hexiege.Application
{
    /// <summary>
    /// 로비에서 확정된 맵(<see cref="MapPreparationResult"/>)을 전투 씬으로 인계하는 정적 홀더.
    /// 씬 재로드를 넘어 값이 살아남아야 하므로 static 으로 둔다.
    /// </summary>
    public static class MapHandoff
    {
        // ====================================================================
        // 상태
        // ====================================================================

        /// <summary>
        /// 아직 아무도 가져가지 않은 "확정된 맵". 없으면 null.
        /// 🔴 외부에 프로퍼티로 노출하지 않는다 — 밖에서 그냥 읽어 갈 수 있게 두면
        ///    아래 TryTake 의 「읽고 비운다」 규칙을 우회하는 샛길이 생기기 때문이다.
        /// </summary>
        private static MapPreparationResult _pending;

        // ====================================================================
        // API
        // ====================================================================

        /// <summary>
        /// 이번 판에 쓸 확정된 맵을 심는다.
        /// Host 는 자기가 만든 결과를, Client 는 받아서 검증을 통과한 결과를 심는다.
        /// 같은 판에 두 번 부르면 나중 값이 앞 값을 덮는다 — 확정된 맵은 판당 하나뿐이므로
        /// 덮어쓰기가 곧 "가장 마지막에 확정된 것이 옳다"는 뜻이 된다.
        /// </summary>
        /// <param name="prepared">확정된 맵 준비 결과(없으면 null 을 넣어 비울 수도 있다)</param>
        public static void Set(MapPreparationResult prepared)
        {
            _pending = prepared;
        }

        /// <summary>
        /// 확정된 맵을 꺼낸다. <b>꺼내는 즉시 내부 보관값을 비운다(읽고 비운다).</b>
        ///
        /// 🔴 왜 「읽고 비운다」로 만들었는가 — 이 설계의 핵심 이유:
        ///    꺼낸 뒤에도 값을 남겨 두면, 다음 판에서 맵 인계가 어떤 이유로든 이루어지지
        ///    않았을 때(전송 실패 · 심는 쪽 코드가 안 불림 · 로비를 거치지 않고 전투 씬에
        ///    바로 들어온 경우 등) <b>지난 판의 맵이 아무 경고 없이 그대로 다시 쓰인다.</b>
        ///    화면에는 멀쩡한 맵이 뜨고 경기도 진행되므로 아무도 이상을 눈치채지 못한다.
        ///    그것이 규칙 16 의 「전투 씬에서는 로비에서 확정한 맵 데이터만 사용해 맵을
        ///    구성한다」를 어기는 <b>가장 조용한 방식</b>이다.
        ///    비워 두면 같은 상황에서 이 함수가 false 를 돌려주므로, 잘못된 맵으로 조용히
        ///    진행되는 대신 "인계된 맵이 없다"는 사실이 호출부에서 곧바로 드러난다.
        ///    즉 이 비우기는 편의가 아니라 <b>오염된 맵을 막는 안전장치</b>다.
        /// </summary>
        /// <param name="prepared">꺼낸 확정 맵(없으면 null)</param>
        /// <returns>꺼낼 값이 있었으면 true, 비어 있었으면 false</returns>
        public static bool TryTake(out MapPreparationResult prepared)
        {
            prepared = _pending;

            // 🔴 반환 여부와 상관없이 무조건 비운다. 위 주석의 이유가 여기서 실행된다.
            _pending = null;

            return prepared != null;
        }

        /// <summary>
        /// 보관 중인 확정 맵을 폐기한다. 로비 복귀 또는 연결 종료 시 호출하는 용도다
        /// (규칙 14 의 "로비 복귀 또는 연결 종료 시 폐기"와 같은 취지).
        ///
        /// ⚠️ 이 메서드는 <b>현재 호출자가 0건이다.</b> 일부러 그렇게 두었다 —
        ///    이번(3단계 C) 범위는 인계 통로를 만드는 것까지이고, 실제로 "언제 폐기할지"를
        ///    배선하는 것은 뒤 단계(F: Host 전송 · I: 씬 전환 게이트)의 몫이다.
        ///    호출자가 없다고 해서 쓰이지 않는 죽은 코드라고 판단해 지우지 말 것.
        /// </summary>
        public static void Clear()
        {
            _pending = null;
        }
    }
}
