// ForcedMapProjectionFailure.cs
//
// 🔴 **에디터 전용 개발 도구.** 「다음 싱글플레이 맵 투영(= 만든 맵을 격자에 새기는
//    단계)을 무조건 실패시킨다」는 1회용 토글의 저장소다.
//
// ┌─ 왜 이런 것이 필요한가 (초급자용 설명) ─────────────────────────────────┐
// │  맵을 쓰는 일은 두 단계다.                                               │
// │    1단계 「만든다」 — 이번 판의 지형·광산 배치를 계산해 설계도를 뽑는다.  │
// │    2단계 「새긴다」 — 그 설계도를 실제 격자(타일)에 대입한다.             │
// │  2단계가 실패하는 경우는 격자 크기나 헥스 방향이 설계도와 맞지 않을 때라  │
// │  **정상적인 프로젝트에서는 한 번도 나지 않는다.**                        │
// │  그래서 이 토글이 없으면 2단계 실패 때 뜨는 화면을 아무도 볼 수 없다.     │
// └──────────────────────────────────────────────────────────────────────────┘
//
// 🔴 **기존 강제 실패 도구로는 이 단계를 태울 수 없다 — 그것이 이 파일이 있는 이유다.**
//    · 멀티 쪽 두 개(맵 전송 계층 · 수락 발신)는 애초에 싱글 경로에 닿지 않는다.
//    · 🔴 **같은 폴더의 「싱글 맵 준비」 토글도 이 단계에 닿지 못한다.** 그 토글은 1단계를
//      실패시키고, 1단계가 실패하면 부르는 쪽이 **곧바로 돌아가 2단계를 아예 부르지 않는다.**
//      즉 토글을 하나만 두고 두 단계에서 함께 읽게 만들면, 1단계가 먼저 소비해 버려서
//      2단계는 **구조적으로 영원히 발동하지 않는다.** 그래서 저장소를 따로 둔다.
//      (담는 값이 둘 다 켜짐/꺼짐이라 「값의 종류가 다르다」는 앞선 선례와는 근거가 다르다 —
//       이번 근거는 **도달 불가**이며, 그쪽이 더 강하다.)
//
// 🔴 릴리스 빌드에서 **통째로 사라진다** — 파일 전체가 에디터 전용 컴파일 가드 안에 있다
//    (아래 using 바로 위의 전처리기 지시문 한 줄 · 파일 맨 끝에서 닫는다).
//    같은 폴더의 「싱글 맵 준비」 토글과 같은 구조다.
//
// 🔴 저장 위치는 **에디터 환경설정 저장소**다(아래 클래스 본문의 키 상수가 그 대상) —
//    씬(.unity)·프리팹(.prefab)에 저장되지 않는다.
//    (그렇게 하는 이유 두 가지는 Infrastructure/Debug/ForcedMapTransferFailure.cs 머리말에
//     적어 두었다. 한 사실을 두 곳에 적지 않는다.)
//    ⚠️ 이 머리말에 그 저장소의 타입 이름을 그대로 적지 않는다 — 「그 타입이 에디터 전용
//       컴파일 가드 밖에서 참조되지 않는가」를 세는 검사가 주석 때문에 오탐하게 된다.
//
// 🔴 **한 번 쓰면 스스로 꺼진다**(1회용). 소비 지점은
//    `GameBootstrapper.ProjectMap()` 한 곳이며, 🔴 **그 자리에서 「싱글인가」를 함께 확인한다** —
//    그 메서드는 싱글과 멀티가 **함께 쓰는 자리**라서 조건 없이 읽으면 멀티도 실패한다.
//
// 조작 수단: 상단 메뉴 `Hexiege/Debug/강제 실패 — 싱글 맵 투영 (다음 1회)`
//            (구현은 Assets/Editor/Debug/ForceRematchMapFailureMenu.cs — 기존 5종과 같은 파일.
//             🔴 그 파일의 「현재 설정 확인」·「해제」는 저장소 **전부**를 함께 다룬다.)
//
// Bootstrap 레이어 — 이 플래그를 보는 GameBootstrapper 도 Bootstrap 이다
//   (멀티 쪽 두 플래그가 그것을 보는 컨트롤러와 같은 Infrastructure 에 있는 것과 같은 관례다).
