// ============================================================================
// TileKind.cs
// 타일 한 칸의 "정적 지형 종류". 맵 정의(MapDefinition)로 결정되며 경기 중 바뀌지 않는다.
//
// 왜 이 enum이 새로 생겼는가:
//   예전에는 타일이 "이동할 수 있는가(IsWalkable)"라는 값 하나를 여기저기서 직접
//   켜고 끄는 방식이었다. 그러면 "이동은 되는데 건물은 못 짓는 타일" 같은 조합을
//   표현할 수 없고, 값을 누가 왜 껐는지도 알 수 없었다.
//   그래서 "지형이 원래 어떤 칸인가"를 이 TileKind 하나로 따로 적어 두고,
//   "이동 가능한가"는 TileKind + MineKind + HasBuilding 세 가지로부터
//   HexTile이 자동으로 계산하도록 바꾸었다.
//
// 왜 "지형 종류"와 "건설 규칙"을 필드 2개로 나누지 않았는가:
//   2개로 나누면 「막혔는데 건설은 허용」처럼 뜻이 없는 조합이 만들어질 수 있고,
//   그 조합 때문에 게임 의미가 같은 맵이 서로 다른 해시(SHA-256)를 갖게 된다.
//   해시는 멀티플레이에서 Host/Client가 같은 맵을 받았는지 확인하는 근거이므로
//   이 어긋남은 치명적이다. 3상태 단일 값이면 모순 조합 자체가 만들어질 수 없다.
//   (근거: TechnicalDesignDocument.md 「MapDefinition 정규 데이터 계약」)
//
// Domain 레이어 — 순수 C#, Unity/Core 의존 없음.
// ============================================================================

namespace Hexiege.Domain
{
    /// <summary>
    /// 타일의 정적 지형 종류(3상태). 맵 정의로 결정되며 경기 중 불변.
    /// 숫자 값은 canonical binary(직렬화)에 그대로 기록되므로 절대 바꾸지 말 것.
    /// </summary>
    public enum TileKind
    {
        /// <summary> 일반 타일 — 이동 O / 점령 O / 일반 건설 O. </summary>
        Normal = 0,

        /// <summary> 건설 불가 타일 — 이동 O / 점령 O / 일반 건설 X (MiningPost는 예외로 허용). </summary>
        NoBuild = 1,

        /// <summary> 막힌 타일 — 이동 X / 점령 X / 건설 X. 건물을 부숴도 열리지 않는 영구 지형. </summary>
        Blocked = 2
    }
}
