// MineKind.cs
// 타일 한 칸에 놓인 "광산의 종류". 맵 정의의 광산 배치 목록에서 로드 시 투영되며
// 경기 중 바뀌지 않는다.
//
// 왜 이 enum이 예전의 "금광 있음" bool 플래그를 대체하는가:
//   예전에는 "금광이 있다/없다"만 알 수 있어서, 그 광산이 Blue 시작 광산인지
//   Red 시작 광산인지 중립 광산인지는 코드가 구분할 방법이 없었다.
//   앞으로 무작위 맵을 만들면 팀별 시작 광산을 180도 대칭으로 배치해야 하므로
//   "누구의 광산인가"를 타일 상태에서 바로 읽을 수 있어야 한다.
//
//   또한 예전에는 광산 타일을 막기 위해 "금광 있음" 플래그와 "이동 불가" 플래그를
//   나란히 두 번 대입했는데, 이제는 MineKind만 설정하면 이동 가능 여부가 자동으로
//   계산된다(HexTile 참조). 대입이 하나로 줄어 "한쪽만 설정해서 어긋나는"
//   실수가 구조적으로 사라진다.
//
// Domain 레이어 — 순수 C#, Unity/Core 의존 없음.
// ============================================================================

namespace Hexiege.Domain
{
    /// <summary>
    /// 타일에 놓인 광산의 종류. None이 아니면 그 타일은 이동 불가이며
    /// 일반 건물 대신 채굴소(MiningPost)만 지을 수 있다.
    /// 숫자 값은 canonical binary(직렬화)에 그대로 기록되므로 절대 바꾸지 말 것.
    /// </summary>
    public enum MineKind
    {
        /// <summary> 광산 없음(대부분의 타일). </summary>
        None = 0,

        /// <summary> 중립 광산 — 어느 팀이든 인접 조건을 만족하면 채굴소를 지을 수 있다. </summary>
        Neutral = 1,

        /// <summary> Blue 팀의 시작 광산 — 경기 시작 시 Blue 채굴소가 자동 건설된다. </summary>
        BlueStart = 2,

        /// <summary> Red 팀의 시작 광산 — 경기 시작 시 Red 채굴소가 자동 건설된다. </summary>
        RedStart = 3
    }
}
