// ============================================================================
// MapType.cs
// 무작위 맵의 "유형"(다섯 가지 모양 중 하나).
//
// 무작위 맵은 아무 모양이나 나오는 것이 아니라, 기획이 정한 다섯 가지 유형 중
// 하나를 먼저 뽑고 그 유형의 규칙에 맞춰 지형을 만든다. 이 enum은 그 다섯 가지를
// 코드에서 가리키기 위한 이름표다.
//
// ⚠️ 이 파일은 1단계에서 "만들어만 두는" 자료구조다.
//    아직 어떤 코드도 이 enum을 사용하지 않으며(맵 생성기는 2단계 작업),
//    지금 게임은 여전히 코드에 하드코딩된 고정 맵을 사용한다.
//
// 근거: GameSystemRules/GameSystemRules_RandomMap.md 3장
//       (완전개방형 · 장애물 개방형 · 협곡형 · 외곽형 · 3갈래형 순서)
//
// Domain 레이어 — 순수 C#, Unity/Core 의존 없음.
// ============================================================================

namespace Hexiege.Domain
{
    /// <summary>
    /// 무작위 맵 유형 5종. 숫자 값은 canonical binary(직렬화)와 해시 계산에
    /// 그대로 기록되므로 절대 바꾸지 말 것 — 값이 바뀌면 같은 맵의 해시가 달라진다.
    /// </summary>
    public enum MapType
    {
        /// <summary> 완전개방형 — 차단 지형이 거의 없는 넓은 평지. </summary>
        FullyOpen = 0,

        /// <summary> 장애물 개방형 — 개방형에 장애물이 흩뿌려진 형태. </summary>
        ObstacleOpen = 1,

        /// <summary> 협곡형 — 중앙이 좁은 통로로 조여진 형태. </summary>
        Canyon = 2,

        /// <summary> 외곽형 — 중앙이 막히고 바깥으로 우회하는 형태. </summary>
        Outer = 3,

        /// <summary> 3갈래형 — 세 갈래 통로로 나뉜 형태. </summary>
        ThreeLane = 4
    }
}
