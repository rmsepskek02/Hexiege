// ============================================================================
// MapRootSeed.cs
// 이번 판의 "root seed"(64비트 정수)를 뽑는 단 하나의 자리.
//
// ─────────────────────────────────────────────────────────────────────────────
// root seed 가 무엇인가 (초급자용 설명)
// ─────────────────────────────────────────────────────────────────────────────
//   무작위 맵은 "아무렇게나" 만들어지지 않는다. 64비트 숫자 하나(root seed)를 넣으면
//   거기서부터 지형·광산·배치가 전부 결정적으로 파생된다(MapRandom / MapRandomStreams).
//   즉 **같은 seed = 같은 맵**이다. 그래서 seed 하나만 알면 그 판의 맵을 나중에
//   똑같이 다시 만들어 볼 수 있고(버그 재현), 멀티플레이에서 양쪽이 같은 맵을
//   갖고 있는지 대조할 수도 있다.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🔴 왜 이 파일이 따로 존재하는가 — 이것이 이 파일의 존재 이유 전부다
// ─────────────────────────────────────────────────────────────────────────────
//   seed 를 뽑는 코드가 **두 군데**에 필요해졌다.
//     · 싱글플레이 → 전투 씬의 GameBootstrapper 가 뽑는다.
//     · 멀티플레이 → Host 가 **로비에서** 뽑아 Client 에게 맵을 보내야 한다
//                   (GameSystemRules_RandomMap.md 규칙 12 — "Host 가 유일한 권위자").
//                   그런데 로비 씬에는 GameBootstrapper 가 아예 없다.
//
//   이때 코드를 복사해 두 벌로 만들면, 언젠가 한쪽만 고쳐지고 다른 쪽은 그대로 남는다.
//   그 순간 "싱글과 멀티가 서로 다른 방식으로 seed 를 뽑는" 상태가 조용히 생기고,
//   아무도 눈치채지 못한다(둘 다 정상으로 보이는 맵을 만들어 내기 때문이다).
//   그래서 **뽑는 방법을 여기 한 곳에만 두고 양쪽이 이것을 불러 쓴다.**
//
// ─────────────────────────────────────────────────────────────────────────────
// 왜 Domain 레이어인가 (레이어 규약 근거)
// ─────────────────────────────────────────────────────────────────────────────
//   이 프로젝트의 의존 방향은 Domain → Application → Core → Infrastructure →
//   Presentation → Bootstrap 이다. 즉 **Domain 은 가장 안쪽이라 모두가 참조할 수 있다.**
//   이 seed 를 써야 하는 두 곳은 Bootstrap(GameBootstrapper)과
//   Infrastructure(NetworkGameManager)인데, 둘 다 Domain 을 참조할 수 있으므로
//   여기에 두면 어느 쪽도 레이어를 거슬러 올라가지 않는다.
//
//   그리고 seed 재료로 쓰면 안 되는 것들(런타임 문자열 해시 · 엔진 전역 난수 등)의
//   근거가 이미 같은 폴더의 MapRandom.cs 머리말에 정리돼 있다. seed 를 만드는 코드가
//   그 설명 바로 옆에 있는 편이, 나중에 "왜 이렇게 뽑나"를 찾는 사람에게 가장 가깝다.
//
//   ⚠️ 이 파일은 시계(현재 시각)와 GUID 를 읽으므로 **호출할 때마다 다른 값**이 나온다.
//      "Domain 은 결정적이어야 한다"는 통념과 어긋나 보일 수 있는데, 결정적이어야 하는
//      것은 **seed 를 넣은 뒤의 생성 과정**이고 seed 자체는 매 판 달라야 한다.
//      그 경계가 정확히 이 파일이다 — 여기서부터 안쪽(MapRandom 이후)은 전부 결정적이다.
//
// ─────────────────────────────────────────────────────────────────────────────
// Domain 레이어 — 순수 C#. UnityEngine · Hexiege.Core 참조 금지.
// ============================================================================

using System;

namespace Hexiege.Domain
{
    /// <summary>
    /// 이번 판의 64비트 root seed 를 뽑는 정적 헬퍼.
    /// 싱글플레이(전투 씬)와 멀티플레이 Host(로비)가 <b>같은 이 함수를</b> 쓴다.
    /// </summary>
    public static class MapRootSeed
    {
        /// <summary>
        /// 매 판 새로운 64비트 root seed 를 만든다.
        ///
        /// 🔴 엔진 난수나 객체 해시 코드를 쓰지 않는다 — 맵 생성 계통에서 그것들을
        ///    쓰지 않기로 한 약속(TechnicalDesignDocument.md 「결정적 PRNG 및 독립 스트림 계약」,
        ///    자세한 이유는 같은 폴더 MapRandom.cs 머리말)과 혼동될 여지를 남기지 않기 위해서다.
        ///    여기서 필요한 것은 "매 판 다른 64비트 값" 하나뿐이므로 시각과 GUID 를 섞는다.
        ///
        /// 만드는 방법(두 재료를 XOR 한다):
        ///   ① GUID 앞 8바이트 — GUID 는 생성될 때마다 전역적으로 겹치지 않도록 만들어지므로
        ///      앞 8바이트만 써도 값이 충분히 흩어진다.
        ///   ② 현재 시각(UTC Ticks) — 같은 프로세스에서 연속으로 시작해도 값이 겹치지 않게
        ///      시간 성분을 한 번 더 섞는다.
        /// </summary>
        /// <returns>이번 판의 root seed</returns>
        public static ulong Create()
        {
            byte[] guidBytes = Guid.NewGuid().ToByteArray();

            ulong entropy = 0UL;
            for (int i = 0; i < 8; i++)
                entropy = (entropy << 8) | guidBytes[i];

            return entropy ^ (ulong)DateTime.UtcNow.Ticks;
        }
    }
}
