// 유닛에 걸리는 "상태효과(버프/디버프/제어/회복)"의 종류를 구분하는 열거형.
//
// 무엇을 구분하나(초급자용 설명):
//   타입 C 스킬(전역 상태변경)은 대상 유닛의 스탯·행동을 일정 시간 동안 바꾼다.
//   버프(공격 강화)·디버프(공격 약화)·제어(둔화/빙결)·회복을 모두 이 하나의 상태변경
//   시스템으로 표현한다(규칙 13). 이 열거형은 "어떤 방식으로 스탯/행동을 바꿀지"를 가리키는 키다.
//
//   ⚠️ 정수 값 고정: 데이터(SkillDefinition._statusKind, int)가 이 열거형 값과 1:1로 매핑되므로
//      기존 멤버의 정수 값을 바꾸지 말 것(직렬화·데이터 안정성). 새 멤버는 뒤에 추가한다.
//
//   각 멤버의 Magnitude(강도) 해석:
//     - MoveSpeedMul   : 이동속도 배율(0<m<1 = 둔화). 예: 0.5 = 이동속도 절반.
//     - AttackPowerMul : 공격력 배율(m>1 = 버프, 0<m<1 = 디버프). 예: 1.5 = 공격력 1.5배.
//     - AttackDisabled : 강도 무시(공격만 봉쇄, 이동은 가능 — 기절 등).
//     - Freeze         : 강도 무시(빙결 = 이동속도 0 + 공격 불가를 하나로 표현 — 규칙 13).
//     - HealOverTime   : 지속 회복 "총량"(HP). 이 종류는 상태 시스템에 저장하지 않고 기존 HoT를
//                        재사용한다(회복 HP는 이미 네트워크로 동기화되므로 상태 배율 합성 대상이 아님).
//
//   ── 2026-11-16 추가(지원 스킬 새 상태 — 단계 A, _Tasks/2026-11-16/01_00_support-skill-new-statuses Plan S-13) ──
//   아래 두 값은 유닛 상태 시스템(StatusEffectSystem)에 넣지 않는다. 서버 전용 「지원 스킬 효과 서비스」
//   (Application/Services/SupportSkillEffectSystem)가 따로 보관한다 — 상태 시스템은 같은 종류를 통째로 교체하고
//   순수 클라이언트 거울에서도 돌기 때문에, 피해 · 생산처럼 서버만 계산해야 하는 효과를 넣으면 안 된다.
//     - IncomingDamageMul  : 받는 피해 배율(0<m<1 = 덜 아프게 맞음). 예: 0.7 = 받는 피해 30% 감소(대지의 갑주).
//                            유닛에만 걸린다. 피해 지점 6곳이 같은 헬퍼(IncomingDamage)로 이 배율을 곱한다.
//     - ProductionSpeedMul : 생산 속도 배율(m>1 = 빨리 만듦). 예: 1.5 = 생산 진행이 1.5배 빠름(전술 지령의 생산 부분).
//                            유닛이 아니라 "팀" 단위로 걸린다(그 팀의 생산 건물 전부 — Plan S-9).
//   ── 2026-11-16 단계 C 추가(Plan 6-1) ──
//     - Shield             : 쉴드 흡수량(예: 150 = 피해 150까지 HP 대신 받아 줌). 유닛 · 건물 모두에 걸린다(신목의 각성).
//   ── 2026-11-17 단계 B 추가(재생의 뿌리, Plan 6-2) ──
//     - Regen              : 재생(예: 20 = 1초마다 HP 20을 되찾음). 유닛 · 건물 모두에 걸린다. 체력이 가득이면 그 순간은 건너뛰고 효과는 남는다.
//     - HealAmpMul         : 받는 회복 배율(예: 1.5 = 이 대상이 받는 회복이 전부 1.5배). 자연회복 · 물안개 · BloomFairy 힐 · 재생의 뿌리
//                            자신의 재생까지 모든 회복에 한 번씩 곱한다. 유닛 · 건물 모두에 걸린다.
//   ── 2026-11-23 연막탄 추가(Plan P-1) ──
//     - EvadeChance        : 회피 확률(예: 0.5 = 50%). 연막(아군 대상 지속 상태 구역) 안의 아군 유닛만. 구역 서비스(SkillZoneSystem)가 보관한다.
//
// Domain 레이어 — 순수 C#. UnityEngine / Hexiege.Core 참조 금지.
// ============================================================================

namespace Hexiege.Domain
{
    /// <summary>
    /// 상태효과(버프/디버프/제어/회복)의 종류. 타입 C 스킬이 부여하며, 유효 스탯 접근자가 배율로 합성한다(규칙 13).
    /// </summary>
    public enum StatusEffectKind
    {
        /// <summary> 없음(기본값). 데이터 미설정 시 무효과. </summary>
        None = 0,

        /// <summary> 이동속도 배율(Magnitude=배율, 0&lt;m&lt;1=둔화). GetUnitMoveSpeedMultiplier에 곱연산 합성. </summary>
        MoveSpeedMul = 1,

        /// <summary> 공격력 배율(Magnitude=배율, m&gt;1=버프/0&lt;m&lt;1=디버프). EffectiveAttack에 곱연산 합성. </summary>
        AttackPowerMul = 2,

        /// <summary> 공격 불가(기절 — 이동은 가능, 공격만 봉쇄). CanAttack 게이트가 false를 반환하게 한다. </summary>
        AttackDisabled = 3,

        /// <summary> 빙결 = 이동속도 0 + 공격 불가(규칙 13). 이동 배율 0 + CanAttack false를 하나로 표현. </summary>
        Freeze = 4,

        /// <summary> 지속 회복(Magnitude=총 회복량 HP). 상태 시스템 미저장 — 기존 HoT(ApplyTimedEffect)로 위임. </summary>
        HealOverTime = 5,

        // ── 2026-11-16 추가 — 서버 전용 지원 스킬 효과 서비스가 보관한다(상태 시스템 · 상태 RPC에 넣지 않는다) ──

        /// <summary>
        /// 받는 피해 배율(Magnitude=배율, 0&lt;m&lt;1=감소). 유닛 전용. 대지의 갑주.
        /// 피해 지점 6곳이 방어 감쇄 "뒤"에 이 배율을 곱한다(반올림 AwayFromZero · 최소 1).
        /// </summary>
        IncomingDamageMul = 6,

        /// <summary>
        /// 생산 속도 배율(Magnitude=배율, m&gt;1=빠름). 팀 단위(그 팀 생산 건물 전부). 전술 지령의 생산 부분.
        /// 생산 진행 시간에 매 틱 곱한다(진행 중인 생산에도 바로 적용 — Plan S-9 안 A).
        /// </summary>
        ProductionSpeedMul = 7,

        // ── 2026-11-16 추가(단계 C — 신목의 각성, Plan 6-1) — 위 두 값과 같이 서버 전용 지원 스킬 효과 서비스가 보관한다 ──

        /// <summary>
        /// 쉴드(Magnitude=흡수량, 정수로 반올림). 유닛 · 건물 모두에 걸 수 있다. 신목의 각성.
        /// 피해 지점 헬퍼(IncomingDamage)가 받는 피해 배율 "뒤"에 남은 쉴드만큼 먼저 흡수하고, 남은 피해만 HP로 넘긴다.
        /// 쉴드가 0이 되면 「깨짐」 — 기록이 사라지고 화면에 알린다. 지속 시간이 끝나면 남은 양은 버린다.
        /// </summary>
        Shield = 8,

        // ── 2026-11-17 추가(단계 B — 재생의 뿌리, Plan 6-2) — 위 값들과 같이 서버 전용 지원 스킬 효과 서비스가 보관한다 ──
        //   🔴 기존 「지속 회복(HealOverTime = 5)」을 쓰지 않는 이유(Plan 6-2-2 · Research 3절 1):
        //     ① 체력이 가득 찬 대상은 첫 틱에 효과가 지워진다 ② BloomFairy 힐과 같은 저장 칸이라 서로 덮어쓴다
        //     ③ 강도가 「초당」이 아니라 「총량」이다 ④ 유닛 상태 VFX 장치(UnitBuffVfxPresenter)가 그 종류를 일부러 건너뛴다.
        //   그래서 재생은 새 값으로 두고, 지원 스킬 효과 서비스의 「독립 재생 채널」이 1초마다 회복시킨다.

        /// <summary>
        /// 재생(Magnitude=초당 회복량 HP). 유닛 · 건물 모두에 걸 수 있다. 재생의 뿌리.
        /// 서버 권위 틱에서 1초마다 「초당 회복량」만큼 회복한다(물안개처럼 1초 주기 — 받는 회복 배율이 있으면 그 배율도 한 번 곱한다).
        /// 체력이 가득이면 그 1초는 건너뛰고 효과는 끝까지 남는다(물안개 규칙 5).
        /// </summary>
        Regen = 9,

        /// <summary>
        /// 받는 회복 배율(Magnitude=배율, m&gt;1=증폭). 유닛 · 건물 모두에 걸 수 있다. 재생의 뿌리.
        /// 회복이 HP에 들어가는 자리(자연회복 · BloomFairy · 지속 회복 · 물안개 유닛 · 물안개 건물 · 재생)에서 한 번만 곱하고,
        /// 정수로 떨어지지 않는 소수는 대상별로 모아 다음 회복에 넘긴다(소수 이월). 효과가 없으면 곱하지 않는다(값 그대로).
        /// </summary>
        HealAmpMul = 10,

        // ── 2026-11-23 추가(연막탄 — _Tasks/2026-11-23/15_28_support-skill-smoke-bomb Plan P-1) ──
        //   유닛 상태 시스템(StatusEffectSystem)에도, 지원 스킬 효과 서비스에도 넣지 않는다.
        //   「지속 상태 구역」 서비스(SkillZoneSystem)만 이 값을 구역 효과로 들고 있다 — 연막 안에 서 있는 동안만 걸리고 나가면 풀린다.

        /// <summary>
        /// 회피 확률(Magnitude=확률 0~1, 예: 0.5 = 50%). 유닛 전용 · 구역 전용(연막탄 — 아군 대상 지속 상태 구역).
        /// 연막 안의 아군 유닛이 적의 원거리 단일 공격을 이 확률로 피한다(피하면 피해 · 화상 · 피해 숫자 없음).
        /// 판정(주사위)은 서버의 회피 판정 서비스가 경기 seed + 공격 열쇠 해시로 한다 — 이 값은 확률만 담는다.
        /// </summary>
        EvadeChance = 11
    }
}
