// ============================================================================
// IGameUI.cs
// 게임 UI 생명주기 인터페이스.
//
// 역할:
//   게임의 주요 상태 변경(시작, 종료) 시
//   각 UI 컴포넌트가 자신의 상태를 적절히 처리할 수 있도록 콜백을 제공.
//
// 사용 방법:
//   1. UI MonoBehaviour에 IGameUI 인터페이스를 구현
//   2. GameUIManager에 Register()로 등록
//   3. 게임 상태 변경 시 GameUIManager가 등록된 UI의 콜백을 호출
//      ⚠️ 종료 콜백만은 "등록된 전부"가 아니다 — 관리자는 결과 화면 UI 하나를 일부러 건너뛴다.
//         결과 화면은 게임이 끝날 때 <닫혀야 하는> UI가 아니라 <떠야 하는> UI이기 때문이다.
//         그 UI는 종료 이벤트를 스스로 구독해 자기 표시를 처리한다.
//
// default interface implementation (C# 8+):
//   모든 메서드에 기본 빈 구현이 있으므로,
//   필요한 콜백만 오버라이드하면 됨. 나머지는 아무것도 하지 않음.
//
// 예시:
//   public class MyUI : MonoBehaviour, IGameUI
//   {
//       // 게임 종료 시 팝업 닫기만 필요한 경우
//       public void OnGameEnded() { Close(); }
//       // OnGameStarted는 default 빈 구현 사용
//   }
//
// Presentation 레이어 — Unity 의존 없음 (순수 C# 인터페이스).
// ============================================================================

namespace Hexiege.Presentation
{
    /// <summary>
    /// 게임 UI 생명주기 인터페이스.
    /// 게임 상태 변경 시 각 UI가 자신의 상태를 정리/초기화할 수 있도록 콜백 제공.
    /// </summary>
    public interface IGameUI
    {
        /// <summary>
        /// 게임 시작 또는 재시작 시 호출.
        /// 맵 로드의 거의 끝에서 발행되므로, 전투에 필요한 시스템은 대부분 준비된 상태다.
        ///
        /// ⚠️ "완전히 끝난 뒤"는 아니다(2026-10-05 실측 — 조합 루트의 맵 로드 절차에서
        ///    이 이벤트를 발행한 <뒤에> 두 단계가 더 남아 있다).
        ///    발행 시점에 아직 안 된 것: 건물 변경 시 유닛 경로를 즉시 다시 계산하게 하는
        ///    구독이 아직 걸리지 않았고, 전역 로딩 표시도 아직 켜져 있다.
        ///    그래서 이 콜백 안에서 "로딩 표시는 이미 꺼졌다"를 전제로 하면 안 된다.
        ///
        /// 기본 구현: 아무것도 하지 않음.
        /// </summary>
        void OnGameStarted() { }

        /// <summary>
        /// 게임 종료 시 호출.
        /// 열려있는 팝업을 닫거나, 입력을 비활성화하는 등의 정리 작업에 사용.
        ///
        /// ⚠️ 종료 사유는 Castle 파괴 하나가 아니다(2026-10-05 실측 — 종료 이벤트를 발행하는
        ///    자리를 전수 확인했다). 세 부류가 모두 이 콜백에 도달한다.
        ///    ① Castle 파괴 — 종료 UseCase 가 판정해 발행.
        ///    ② 포기 — 싱글은 같은 UseCase 가, 멀티는 서버가 받아 발행.
        ///    ③ 상대 연결 끊김으로 남은 쪽이 승리 처리 — 네트워크 종료 컨트롤러가 발행.
        ///    즉 "성이 깨졌으니 전투가 있었다"를 전제로 하는 정리 코드를 여기에 두면 안 된다.
        ///
        /// 기본 구현: 아무것도 하지 않음.
        /// </summary>
        void OnGameEnded() { }
    }
}
